using Kovsie_Living.Models; 
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using System.Text.Json;

namespace Kovsie_Living.Data.Repositories
{
    public class PdfService
    {
        public byte[] GenerateReportPdf(Report report)
        {
            QuestPDF.Settings.License = LicenseType.Community;

            var document = Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(2, Unit.Centimetre);
                    page.DefaultTextStyle(x => x.FontSize(10));

                    page.Header().Element(container => ComposeHeader(container, report));
                    page.Content().Element(container => ComposeContent(container, report));
                    page.Footer().AlignCenter().Text(x =>
                    {
                        x.Span($"Generated by Kovsie Living - {report.GeneratedDate:dd MMM yyyy HH:mm}");
                    });
                });
            });

            return document.GeneratePdf();
        }

        private void ComposeHeader(IContainer container, Report report)
        {
            container.Column(column =>
            {
                column.Item().Text(report.Title)
                    .FontSize(18)
                    .Bold();

                column.Item().Text($"Report Type: {report.ReportType}")
                    .FontSize(12)
                    .FontColor(Colors.Grey.Darken1);

                column.Item().Text($"Date Range: {report.StartDate:dd MMM yyyy} - {report.EndDate:dd MMM yyyy}")
                    .FontSize(10)
                    .FontColor(Colors.Grey.Darken1);

                column.Item().PaddingTop(5).LineHorizontal(1).LineColor(Colors.Grey.Lighten2);
            });
        }

        private void ComposeContent(IContainer container, Report report)
        {
            container.PaddingVertical(10).Column(column =>
            {
                column.Spacing(10);

                if (!string.IsNullOrEmpty(report.ReportDataJson))
                {
                    switch (report.ReportType)
                    {
                        case "Customers":
                            var customerData = JsonSerializer.Deserialize<CustomerReportData>(report.ReportDataJson);
                            if (customerData != null)
                                ComposeCustomerReport(column, customerData);
                            break;
                        case "Payments":
                            var paymentData = JsonSerializer.Deserialize<PaymentReportData>(report.ReportDataJson);
                            if (paymentData != null)
                                ComposePaymentReport(column, paymentData);
                            break;
                        case "Revenue":
                            var revenueData = JsonSerializer.Deserialize<RevenueReportData>(report.ReportDataJson);
                            if (revenueData != null)
                                ComposeRevenueReport(column, revenueData);
                            break;
                    }
                }
            });
        }

        private void ComposeCustomerReport(ColumnDescriptor column, CustomerReportData data)
        {
            // Summary Cards
            column.Item().Row(row =>
            {
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Total Customers", data.TotalCustomers.ToString(), Colors.Blue.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Approved", data.ApprovedCustomers.ToString(), Colors.Green.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Pending", data.PendingCustomers.ToString(), Colors.Orange.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Total Collected", $"R {data.TotalCollected:N2}", Colors.Green.Darken1));
            });

            column.Item().PaddingTop(10).Text("Customer Details").FontSize(14).Bold();

            // Customer Table
            column.Item().Table(table =>
            {
                table.ColumnsDefinition(columns =>
                {
                    columns.RelativeColumn(3);
                    columns.RelativeColumn(1);
                    columns.RelativeColumn(2);
                    columns.RelativeColumn(1);
                    columns.RelativeColumn(1);
                    columns.RelativeColumn(2);
                    columns.RelativeColumn(2);
                });

                table.Header(header =>
                {
                    header.Cell().Element(CellStyle).Text("Name").Bold();
                    header.Cell().Element(CellStyle).Text("Type").Bold();
                    header.Cell().Element(CellStyle).Text("Number").Bold();
                    header.Cell().Element(CellStyle).Text("Unit").Bold();
                    header.Cell().Element(CellStyle).Text("Status").Bold();
                    header.Cell().Element(CellStyle).Text("Registered").Bold();
                    header.Cell().Element(CellStyle).Text("Total Paid").Bold();
                });

                foreach (var customer in data.Customers)
                {
                    table.Cell().Element(CellStyle).Text(customer.FullName);
                    table.Cell().Element(CellStyle).Text(customer.UserType);
                    table.Cell().Element(CellStyle).Text(customer.UserNumber);
                    table.Cell().Element(CellStyle).Text(customer.UnitNumber);
                    table.Cell().Element(CellStyle).Text(customer.Status);
                    table.Cell().Element(CellStyle).Text(customer.RegistrationDate.ToString("dd MMM yyyy"));
                    table.Cell().Element(CellStyle).Text($"R {customer.TotalPaid:N2}");
                }
            });
        }

        private void ComposePaymentReport(ColumnDescriptor column, PaymentReportData data)
        {
            // Summary Cards
            column.Item().Row(row =>
            {
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Total Payments", data.TotalPayments.ToString(), Colors.Blue.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Approved", data.ApprovedPayments.ToString(), Colors.Green.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Pending", data.PendingPayments.ToString(), Colors.Orange.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Total Amount", $"R {data.TotalAmount:N2}", Colors.Green.Darken1));
            });

            column.Item().PaddingTop(10).Text("Payment Details").FontSize(14).Bold();

            // Payment Table
            column.Item().Table(table =>
            {
                table.ColumnsDefinition(columns =>
                {
                    columns.RelativeColumn(3);
                    columns.RelativeColumn(2);
                    columns.RelativeColumn(2);
                    columns.RelativeColumn(2);
                    columns.RelativeColumn(2);
                    columns.RelativeColumn(2);
                });

                table.Header(header =>
                {
                    header.Cell().Element(CellStyle).Text("Customer").Bold();
                    header.Cell().Element(CellStyle).Text("Service").Bold();
                    header.Cell().Element(CellStyle).Text("Amount").Bold();
                    header.Cell().Element(CellStyle).Text("Date").Bold();
                    header.Cell().Element(CellStyle).Text("Status").Bold();
                    header.Cell().Element(CellStyle).Text("Reference").Bold();
                });

                foreach (var payment in data.Payments)
                {
                    table.Cell().Element(CellStyle).Text(payment.CustomerName);
                    table.Cell().Element(CellStyle).Text(payment.TariffName);
                    table.Cell().Element(CellStyle).Text($"R {payment.Amount:N2}");
                    table.Cell().Element(CellStyle).Text(payment.PaymentDate.ToString("dd MMM yyyy"));
                    table.Cell().Element(CellStyle).Text(payment.Status);
                    table.Cell().Element(CellStyle).Text(payment.Reference);
                }
            });
        }

        private void ComposeRevenueReport(ColumnDescriptor column, RevenueReportData data)
        {
            // Summary Cards
            column.Item().Row(row =>
            {
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Total Revenue", $"R {data.TotalRevenue:N2}", Colors.Green.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Pending Revenue", $"R {data.PendingRevenue:N2}", Colors.Orange.Darken2));
                row.RelativeItem().Element(c => CreateSummaryCard(c, "Transactions", data.TransactionCount.ToString(), Colors.Blue.Darken2));
            });

            column.Item().PaddingTop(10).Text("Revenue by Tariff").FontSize(14).Bold();

            // Revenue by Tariff Table
            column.Item().Table(table =>
            {
                table.ColumnsDefinition(columns =>
                {
                    columns.RelativeColumn(3);
                    columns.RelativeColumn(2);
                });

                table.Header(header =>
                {
                    header.Cell().Element(CellStyle).Text("Service").Bold();
                    header.Cell().Element(CellStyle).Text("Amount").Bold();
                });

                foreach (var item in data.RevenueByTariff)
                {
                    table.Cell().Element(CellStyle).Text(item.Key);
                    table.Cell().Element(CellStyle).Text($"R {item.Value:N2}");
                }
            });

            column.Item().PaddingTop(10).Text("Monthly Breakdown").FontSize(14).Bold();

            // Monthly Breakdown Table
            column.Item().Table(table =>
            {
                table.ColumnsDefinition(columns =>
                {
                    columns.RelativeColumn(3);
                    columns.RelativeColumn(2);
                });

                table.Header(header =>
                {
                    header.Cell().Element(CellStyle).Text("Month").Bold();
                    header.Cell().Element(CellStyle).Text("Amount").Bold();
                });

                foreach (var item in data.MonthlyBreakdown)
                {
                    table.Cell().Element(CellStyle).Text(item.Key);
                    table.Cell().Element(CellStyle).Text($"R {item.Value:N2}");
                }
            });
        }

        private void CreateSummaryCard(IContainer container, string label, string value, Color color)
        {
            container
                .Border(1)
                .BorderColor(Colors.Grey.Lighten2)
                .Padding(5)
                .Column(column =>
                {
                    column.Item().Text(label)
                        .FontSize(8)
                        .FontColor(Colors.Grey.Darken1);
                    column.Item().Text(value)
                        .FontSize(12)
                        .Bold()
                        .FontColor(color);
                });
        }

        private IContainer CellStyle(IContainer container)
        {
            return container
                .BorderBottom(1)
                .BorderColor(Colors.Grey.Lighten2)
                .PaddingVertical(5)
                .PaddingHorizontal(3);
        }
    }
}